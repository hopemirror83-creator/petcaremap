import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = process.cwd();
const NAVER_FILE = path.join(ROOT, 'data', 'naver-local-businesses.json');
const REVIEW_FILE = path.join(ROOT, 'data', 'naver-review-sources.json');
const GENERATED_FILE = path.join(ROOT, 'data', 'generated-review-pages.json');
const OUTPUT = path.join(ROOT, 'data', 'd1-enrichment.sql');

const naverRows = await readJson(NAVER_FILE, []);
const reviewRows = await readJson(REVIEW_FILE, []);
const generatedRows = await readJson(GENERATED_FILE, []);

const lines = [
  '-- Generated by scripts/write-d1-enrichment-sql.mjs',
  '-- Stores Naver local signals, review source candidates, and Gemini page text.',
  ''
];

for (const row of naverRows) {
  lines.push(
    `UPDATE businesses SET ${[
      `display_name = ${sql(row.displayName)}`,
      `category = ${sql(row.category)}`,
      `road_address = COALESCE(${sql(row.roadAddress)}, road_address)`,
      `lot_address = COALESCE(${sql(row.lotAddress)}, lot_address)`,
      `phone = COALESCE(${sql(row.phone)}, phone)`,
      `mapx = COALESCE(${num(row.mapx)}, mapx)`,
      `mapy = COALESCE(${num(row.mapy)}, mapy)`,
      `naver_map_url = COALESCE(${sql(row.naverMapUrl)}, naver_map_url)`,
      `updated_at = CURRENT_TIMESTAMP`
    ].join(', ')} WHERE source_id = ${sql(row.sourceId)};`
  );
}

for (const row of reviewRows) {
  lines.push(`DELETE FROM review_sources WHERE business_id = (SELECT id FROM businesses WHERE source_id = ${sql(row.sourceId)});`);
  for (const ref of row.sourceRefs || []) {
    if (!ref.link) continue;
    lines.push(
      `INSERT OR IGNORE INTO review_sources (business_id, source_type, title, url, excerpt, published_at, collected_at) SELECT id, ${sql(ref.sourceType || 'blog')}, ${sql(ref.title)}, ${sql(ref.link)}, ${sql(ref.summary)}, ${sql(ref.postDate)}, ${sql(row.collectedAt)} FROM businesses WHERE source_id = ${sql(row.sourceId)};`
    );
  }
}

for (const row of generatedRows) {
  lines.push(`DELETE FROM generated_pages WHERE business_id = (SELECT id FROM businesses WHERE source_id = ${sql(row.sourceId)});`);
  lines.push(
    `INSERT INTO generated_pages (business_id, title, meta_description, intro_section, service_section, check_section, review_section, field_note_section, caution_points, generated_by, generated_at) SELECT id, ${sql(row.title)}, ${sql(row.metaDescription)}, ${sql(row.introSection)}, ${sql(row.serviceSection)}, ${sql(row.checkSection)}, ${sql(row.reviewSection)}, ${sql(row.fieldNoteSection)}, ${sql(JSON.stringify(row.cautionPoints || []))}, ${sql(row.generatedBy || 'template')}, ${sql(row.generatedAt)} FROM businesses WHERE source_id = ${sql(row.sourceId)};`
  );
}

await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, `${lines.join('\n')}\n`, 'utf8');

console.log(`Naver local rows: ${naverRows.length}`);
console.log(`Review source businesses: ${reviewRows.length}`);
console.log(`Generated pages: ${generatedRows.length}`);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${lines.length} statements)`);

async function readJson(file, fallback = []) {
  try {
    return JSON.parse(await readFile(file, 'utf8'));
  } catch {
    return fallback;
  }
}

function sql(value) {
  if (value === undefined || value === null || value === '') return 'NULL';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function num(value) {
  const number = Number(value);
  return Number.isFinite(number) ? String(number) : 'NULL';
}
